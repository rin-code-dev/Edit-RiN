#!/usr/bin/env python3
"""Convert selected app vector icons to the manual's SVG sprite (no Android edits)."""
from pathlib import Path
import xml.etree.ElementTree as ET
root = Path(__file__).resolve().parents[1]
ns = '{http://schemas.android.com/apk/res/android}'
names = 'add back close code compare dice pin pin_filled pause play reload tune camera history save settings folder_code more_vertical search undo redo fold scrub pip_resize pip_opacity pip_minimize snapshot restore record stop share_card tag delete copy fullscreen assets help'.split()
parts = ['<svg xmlns="http://www.w3.org/2000/svg"><!-- Generated by scripts/build-guide-icons.py from Android vector drawables. -->']
for name in names:
    vector = ET.parse(root / f'android/app/src/main/res/drawable/ic_{name}.xml').getroot()
    parts.append(f'<symbol id="{name}" viewBox="0 0 {vector.get(ns+"viewportWidth")} {vector.get(ns+"viewportHeight")}">')
    for path in vector.iter('path'):
        color = path.get(ns+'fillColor', '#00000000')
        attrs = {'d': path.get(ns+'pathData'), 'fill': 'none' if color in ('#00000000', '@android:color/transparent') else 'currentColor'}
        for android, svg in [('strokeWidth','stroke-width'), ('strokeLineCap','stroke-linecap'), ('strokeLineJoin','stroke-linejoin'), ('fillAlpha','fill-opacity'), ('strokeAlpha','stroke-opacity')]:
            if path.get(ns+android): attrs[svg] = path.get(ns+android)
        if path.get(ns+'strokeColor'): attrs['stroke'] = 'currentColor'
        parts.append(ET.tostring(ET.Element('path', attrs), encoding='unicode'))
    parts.append('</symbol>')
parts.append('</svg>')
(root / 'website/assets/guide/app-icons.svg').write_text('\n'.join(parts))
